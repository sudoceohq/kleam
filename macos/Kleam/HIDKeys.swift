import Foundation
import IOKit
import IOKit.hid

/// Keyboard reports from the device. The lock screen does not deliver letter
/// key-down events to an NSEvent monitor, but it still delivers these.
final class HIDKeyboard {
    var onKey: ((UInt16, Bool) -> Void)?

    private var manager: IOHIDManager?
    private var started = false

    static func accessGranted() -> Bool {
        IOHIDCheckAccess(kIOHIDRequestTypeListenEvent) == kIOHIDAccessTypeGranted
    }

    static func requestAccess() {
        _ = IOHIDRequestAccess(kIOHIDRequestTypeListenEvent)
    }

    func start() {
        guard !started else { return }
        let manager = IOHIDManagerCreate(kCFAllocatorDefault, IOOptionBits(kIOHIDOptionsTypeNone))
        let matching: [[String: Int]] = [
            [
                kIOHIDDeviceUsagePageKey: kHIDPage_GenericDesktop,
                kIOHIDDeviceUsageKey: kHIDUsage_GD_Keyboard,
            ],
            [
                kIOHIDDeviceUsagePageKey: kHIDPage_GenericDesktop,
                kIOHIDDeviceUsageKey: kHIDUsage_GD_Keypad,
            ],
        ]
        IOHIDManagerSetDeviceMatchingMultiple(manager, matching as CFArray)
        let context = Unmanaged.passUnretained(self).toOpaque()
        IOHIDManagerRegisterInputValueCallback(manager, { context, result, _, value in
            guard result == kIOReturnSuccess, let context else { return }
            let keyboard = Unmanaged<HIDKeyboard>.fromOpaque(context).takeUnretainedValue()
            keyboard.handle(value)
        }, context)
        IOHIDManagerScheduleWithRunLoop(manager, CFRunLoopGetMain(), CFRunLoopMode.defaultMode.rawValue)
        let status = IOHIDManagerOpen(manager, IOOptionBits(kIOHIDOptionsTypeNone))
        guard status == kIOReturnSuccess else { return }
        self.manager = manager
        started = true
    }

    private func handle(_ value: IOHIDValue) {
        let element = IOHIDValueGetElement(value)
        guard IOHIDElementGetUsagePage(element) == UInt32(kHIDPage_KeyboardOrKeypad) else { return }
        guard IOHIDElementGetLogicalMax(element) <= 1 else { return }
        let usage = IOHIDElementGetUsage(element)
        guard let keyCode = Self.macKeyCode(forHIDUsage: usage) else { return }
        onKey?(keyCode, IOHIDValueGetIntegerValue(value) != 0)
    }

    /// USB HID keyboard usage → macOS virtual key code.
    private static func macKeyCode(forHIDUsage usage: UInt32) -> UInt16? {
        hidToMac[usage]
    }

